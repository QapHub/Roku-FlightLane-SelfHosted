import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import process from "node:process";
import { REPO_ROOT, parseArgs, readEnvFile, resolveEnvPath, runMain } from "./lib/common.mjs";
import { createRadarPng, createSolidJpeg } from "./lib/images.mjs";
import { createZip } from "./lib/zip.mjs";

const STATIC_ASSET_NAMES = [
  "remote-dpad.png",
  "remote-ok.png",
  "remote-options.png",
  "remote-back.png",
  "flightlane-icon-v2_FHD.png",
  "flightlane-icon-v2_HD.png",
  "flightlane-icon-v2_SD.png",
  "splash-screen_FHD.jpg",
  "splash-screen_HD.jpg",
  "splash-screen_SD.jpg",
];

function readNumber(value, fallback) {
  const parsed = Number.parseFloat(String(value ?? ""));
  return Number.isFinite(parsed) ? parsed : fallback;
}

function formatNumber(value, decimals) {
  return String(Number(value.toFixed(decimals)));
}

// Identifies the exact build on screen: the git commit, plus "+" for uncommitted changes.
function gitBuildId() {
  const run = (args) => spawnSync("git", args, { cwd: REPO_ROOT, encoding: "utf8" });
  const commit = run(["rev-parse", "--short", "HEAD"]);
  if (commit.status !== 0) return "";
  const dirty = run(["status", "--porcelain", "--untracked-files=no"]).stdout.trim() !== "";
  return commit.stdout.trim() + (dirty ? "+" : "");
}

function brightScriptString(value) {
  return String(value).replaceAll('"', '""');
}

export function buildPackage({ environmentFile = ".env.local", screenSaver = false } = {}) {
  const environmentPath = resolveEnvPath(environmentFile);
  const config = readEnvFile(
    environmentPath,
    `Missing ${environmentFile}. Copy .env.example to .env.local and fill in the values.`,
  );

  const generatedPath = path.join(REPO_ROOT, "source", "config.generated.brs");
  const imageRoot = path.join(REPO_ROOT, "images");
  const radarImagePath = path.join(imageRoot, "radar-bg.png");
  const mapBackdropPath = path.join(imageRoot, "map-backdrop.jpg");
  const stageRoot = path.join(REPO_ROOT, "out", screenSaver ? "package-screensaver" : "package");
  const distRoot = path.join(REPO_ROOT, "dist");
  const packagePath = path.join(distRoot, screenSaver ? "flight-lane-screensaver.zip" : "flight-lane.zip");

  const appName = brightScriptString(config.APP_NAME ?? "Flight Lane");
  const latitude = 0.0;
  const longitude = 0.0;
  const radiusMiles = readNumber(config.RADIUS_MILES ?? "4", 4.0);
  let refreshSeconds = readNumber(config.REFRESH_SECONDS ?? "15", 15.0);
  const flightLaneApiUrl = brightScriptString(String(config.FLIGHTLANE_API_URL ?? "").replace(/\/+$/, ""));

  const hasLocation = false;
  if (radiusMiles < 1 || radiusMiles > 10) {
    throw new Error("RADIUS_MILES must be from 1 to 10.");
  }
  if (refreshSeconds < 5) refreshSeconds = 5.0;
  if (!flightLaneApiUrl.trim()) {
    throw new Error(
      "FLIGHTLANE_API_URL is required. Use the private-LAN address of this computer's local service.",
    );
  }
  let serviceUri;
  try {
    serviceUri = new URL(flightLaneApiUrl);
  } catch {
    throw new Error("FLIGHTLANE_API_URL must be a valid HTTP or HTTPS URL.");
  }
  if (serviceUri.protocol !== "http:" && serviceUri.protocol !== "https:") {
    throw new Error("FLIGHTLANE_API_URL must use HTTP or HTTPS.");
  }
  if (serviceUri.hostname === "localhost" || serviceUri.hostname === "127.0.0.1") {
    throw new Error(
      "FLIGHTLANE_API_URL cannot use localhost because the Roku must reach this computer over your private network.",
    );
  }

  const satelliteMapEnabled = flightLaneApiUrl.trim().length > 0;
  let radarPixelsPerMile = 390.0 / radiusMiles;
  let mapZoom = 0;
  if (satelliteMapEnabled) {
    const latitudeRadians = (latitude * Math.PI) / 180.0;
    for (let candidateZoom = 21; candidateZoom >= 0; candidateZoom -= 1) {
      const metersPerLogicalPixel = (156543.03392 * Math.cos(latitudeRadians)) / 2 ** candidateZoom;
      const candidatePixelsPerMile = (1609.344 / metersPerLogicalPixel) * (840.0 / 640.0);
      if (candidatePixelsPerMile * radiusMiles <= 390.0) {
        mapZoom = candidateZoom;
        radarPixelsPerMile = candidatePixelsPerMile;
        break;
      }
    }
  }

  const closeupRadiusFeet = 1000.0;
  const closeupViewportSize = 320.0;
  const closeupRadarRadiusPixels = 390.0 * (closeupViewportSize / 840.0);
  const closeupRadarPixelsPerFoot = closeupRadarRadiusPixels / closeupRadiusFeet;
  const closeupMaxZoom = 17;

  const generated = `' Generated by scripts/build.mjs. Do not commit this file.
function GetAppConfig() as object
    return {
        appName: "${appName}"
        hasLocation: ${hasLocation}
        homeLatitude: ${formatNumber(latitude, 6)}
        homeLongitude: ${formatNumber(longitude, 6)}
        radiusMiles: ${formatNumber(radiusMiles, 3)}
        refreshSeconds: ${formatNumber(refreshSeconds, 3)}
        radarPixelsPerMile: ${formatNumber(radarPixelsPerMile, 6)}
        satelliteMapEnabled: ${satelliteMapEnabled}
        mapZoom: ${mapZoom}
        closeupRadiusFeet: ${formatNumber(closeupRadiusFeet, 0)}
        closeupViewportSize: ${formatNumber(closeupViewportSize, 0)}
        closeupRadarPixelsPerFoot: ${formatNumber(closeupRadarPixelsPerFoot, 6)}
        closeupMaxZoom: ${closeupMaxZoom}
        flightLaneApiUrl: "${flightLaneApiUrl}"
        buildId: "${brightScriptString(gitBuildId())}"
    }
end function
`;
  fs.writeFileSync(generatedPath, generated, "utf8");

  fs.mkdirSync(imageRoot, { recursive: true });
  fs.writeFileSync(mapBackdropPath, createSolidJpeg(840, 840, [8, 24, 39]));
  fs.writeFileSync(radarImagePath, createRadarPng(390.0));

  if (!stageRoot.startsWith(REPO_ROOT + path.sep)) {
    throw new Error("Refusing to clean a staging path outside the repository.");
  }
  fs.rmSync(stageRoot, { recursive: true, force: true });
  fs.mkdirSync(stageRoot, { recursive: true });

  fs.copyFileSync(path.join(REPO_ROOT, "manifest"), path.join(stageRoot, "manifest"));
  fs.cpSync(path.join(REPO_ROOT, "source"), path.join(stageRoot, "source"), { recursive: true });
  fs.cpSync(path.join(REPO_ROOT, "components"), path.join(stageRoot, "components"), { recursive: true });
  const stageImages = path.join(stageRoot, "images");
  fs.mkdirSync(stageImages, { recursive: true });
  for (const imagePath of [radarImagePath, mapBackdropPath]) {
    fs.copyFileSync(imagePath, path.join(stageImages, path.basename(imagePath)));
  }
  for (const staticAssetName of STATIC_ASSET_NAMES) {
    const staticAssetPath = path.join(imageRoot, staticAssetName);
    if (!fs.existsSync(staticAssetPath)) {
      throw new Error(`Missing packaged image asset: ${staticAssetPath}`);
    }
    fs.copyFileSync(staticAssetPath, path.join(stageImages, staticAssetName));
  }
  if (screenSaver) {
    fs.copyFileSync(path.join(REPO_ROOT, "screensaver", "manifest"), path.join(stageRoot, "manifest"));
    fs.copyFileSync(
      path.join(REPO_ROOT, "screensaver", "source", "main.brs"),
      path.join(stageRoot, "source", "main.brs"),
    );
  }

  fs.mkdirSync(distRoot, { recursive: true });
  fs.rmSync(packagePath, { force: true });
  createZip(packagePath, stageRoot, ["manifest", "source", "components", "images"]);

  console.log(`Built ${packagePath}`);
  return packagePath;
}

if (import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  runMain(() => {
    const options = parseArgs();
    buildPackage({
      environmentFile: options["env-file"] || ".env.local",
      screenSaver: Boolean(options.screensaver),
    });
  });
}
